select
    `hash` as transaction_hash,
    block_number,
    block_timestamp,
    date(block_timestamp) as block_date,
    transaction_index,
    nonce,
    from_address,
    to_address,
    value as value_wei,
    cast(value as float64) / 1e18 as value_eth,
    gas as gas_limit,
    gas_price,
    receipt_gas_used as gas_used,
    receipt_effective_gas_price as effective_gas_price,
    max_fee_per_gas,
    max_priority_fee_per_gas,
    transaction_type,
    receipt_status = 1 as is_success,
    receipt_contract_address as created_contract_address,
    substr(input, 1, 10) as method_id,
    div(greatest(length(input) - 2, 0), 2) as input_bytes,
    _loaded_at
from {{ source('eth_raw', 'transactions') }}
